#!/usr/bin/env python3
"""Generate the portal's wire types from the pydantic models.

Writes ``web/src/api/schema.json`` (JSON Schema of every model in
``pyaerial.api.models``) and ``web/src/api/generated.ts`` (TypeScript emitted
from that schema). Both are checked in; ``tests/test_wire_models.py`` fails
when they are stale.

    python scripts/gen_types.py          # rewrite both files
    python scripts/gen_types.py --check  # exit 1 if either is stale

The TypeScript emitter is deliberately small and dependency-free: it covers
the subset of JSON Schema that pydantic produces for these models (objects,
``$ref``, ``anyOf``/``oneOf``, ``const``/``enum``, arrays, tuples via
``prefixItems``, string-keyed maps) and fails loudly on anything else.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
SCHEMA_PATH = ROOT / "web" / "src" / "api" / "schema.json"
TS_PATH = ROOT / "web" / "src" / "api" / "generated.ts"
COMMAND = "python scripts/gen_types.py"

_REF_PREFIX = "#/$defs/"
_PRIMITIVES = {
    "string": "string",
    "number": "number",
    "integer": "number",
    "boolean": "boolean",
    "null": "null",
}
# Keywords that only describe or constrain values TypeScript cannot express.
_IGNORED = frozenset(
    {"title", "description", "default", "minItems", "maxItems", "discriminator"}
)


def schema_text() -> str:
    """``schema.json`` contents: sorted keys, two-space indent, newline-terminated."""
    sys.path.insert(0, str(ROOT / "src"))
    from pyaerial.api.models import wire_json_schema

    schema = {
        "$comment": f"Generated by {COMMAND} from pyaerial.api.models. Do not edit.",
        **wire_json_schema(),
    }
    return json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


class SchemaError(ValueError):
    """The schema uses something the emitter does not support."""


def _ts_string(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def _ts_literal(value: Any, where: str) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None:
        return "null"
    if isinstance(value, str):
        return _ts_string(value)
    if isinstance(value, (int, float)):
        return json.dumps(value)
    raise SchemaError(f"{where}: unsupported literal {value!r}")


def _union(members: list[str]) -> str:
    unique = list(dict.fromkeys(members))
    return " | ".join(unique)


def _array_item(ts: str) -> str:
    return f"({ts})[]" if " | " in ts else f"{ts}[]"


def _ts_type(schema: dict[str, Any], where: str) -> str:
    unknown = set(schema) - _IGNORED - {
        "$ref",
        "anyOf",
        "oneOf",
        "const",
        "enum",
        "type",
        "items",
        "prefixItems",
        "properties",
        "required",
        "additionalProperties",
    }
    if unknown:
        raise SchemaError(f"{where}: unsupported keywords {sorted(unknown)}")
    if "$ref" in schema:
        ref = schema["$ref"]
        if not ref.startswith(_REF_PREFIX):
            raise SchemaError(f"{where}: unsupported $ref {ref!r}")
        return ref[len(_REF_PREFIX) :]
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return _union(
                [_ts_type(item, f"{where}.{key}") for item in schema[key]]
            )
    if "const" in schema:
        return _ts_literal(schema["const"], where)
    if "enum" in schema:
        return _union([_ts_literal(v, where) for v in schema["enum"]])
    kind = schema.get("type")
    if kind in _PRIMITIVES:
        return _PRIMITIVES[kind]
    if kind == "array":
        if "prefixItems" in schema:
            items = [
                _ts_type(item, f"{where}.prefixItems")
                for item in schema["prefixItems"]
            ]
            if schema.get("items") not in (None, False) or schema.get(
                "maxItems"
            ) != len(items):
                raise SchemaError(f"{where}: only fixed-length tuples are supported")
            return "[" + ", ".join(items) + "]"
        if "items" not in schema:
            return "unknown[]"
        return _array_item(_ts_type(schema["items"], f"{where}.items"))
    if kind == "object":
        if schema.get("properties"):
            raise SchemaError(f"{where}: inline objects must be models ($defs)")
        values = schema.get("additionalProperties", True)
        if values is True:
            return "Record<string, unknown>"
        return f"Record<string, {_ts_type(values, where + '.additionalProperties')}>"
    raise SchemaError(f"{where}: unsupported schema {schema!r}")


def _doc(text: str | None, indent: str) -> list[str]:
    if not text:
        return []
    lines = [line.rstrip() for line in text.replace("``", "`").strip().splitlines()]
    lines = [line.replace("*/", "*\\/") for line in lines]
    if len(lines) == 1:
        return [f"{indent}/** {lines[0]} */"]
    body = [f"{indent} *{' ' + line if line else ''}" for line in lines]
    return [f"{indent}/**", *body, f"{indent} */"]


def _definition(name: str, schema: dict[str, Any]) -> list[str]:
    out = _doc(schema.get("description"), "")
    if schema.get("type") == "object" and "properties" in schema:
        if schema.get("additionalProperties", True) is not False:
            raise SchemaError(f"{name}: models must forbid extra keys")
        required = set(schema.get("required", ()))
        out.append(f"export interface {name} {{")
        for prop, prop_schema in schema["properties"].items():
            out.extend(_doc(prop_schema.get("description"), "  "))
            optional = "" if prop in required else "?"
            ts = _ts_type(prop_schema, f"{name}.{prop}")
            out.append(f"  {prop}{optional}: {ts};")
        out.append("}")
        return out
    out.append(f"export type {name} = {_ts_type(schema, name)};")
    return out


def typescript(schema: dict[str, Any]) -> str:
    """TypeScript declarations for every ``$defs`` entry, sorted by name."""
    lines = [
        f"// Generated by `{COMMAND}` from schema.json (pyaerial.api.models).",
        "// Do not edit: change the models and regenerate.",
    ]
    definitions = schema.get("$defs", {})
    for name in sorted(definitions):
        lines.append("")
        lines.extend(_definition(name, definitions[name]))
    return "\n".join(lines) + "\n"


def render() -> dict[Path, str]:
    """Expected contents of every generated file."""
    text = schema_text()
    return {SCHEMA_PATH: text, TS_PATH: typescript(json.loads(text))}


def stale_files() -> list[Path]:
    return [
        path
        for path, text in render().items()
        if not path.exists() or path.read_text(encoding="utf-8") != text
    ]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="exit 1 if a generated file is stale"
    )
    args = parser.parse_args(argv)
    if args.check:
        stale = stale_files()
        for path in stale:
            print(f"{path.relative_to(ROOT)} is stale; run: {COMMAND}", file=sys.stderr)
        return 1 if stale else 0
    for path, text in render().items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
